    private void btnTranferirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTranferirActionPerformed
// 1. Obtener datos de los cuadros de texto
    String cuentaDestino = NumeroCuenta.getText().trim();
    String montoTexto = CuadroMonto.getText().trim();

    // 2. Validación simple de campos vacíos
    if (cuentaDestino.isEmpty() || montoTexto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos.");
        return;
    }

    try (Connection con = new conexion().conectar()) { 
        con.setAutoCommit(false);
        
        double monto = Double.parseDouble(montoTexto);
        int idEmisor = this.idUsuarioLogueado; 

        // 3. BUSCAR AL EMISOR
        String sqlCheck = "SELECT c.CUE_id, c.CUE_saldo FROM CUENTAS c WHERE c.CLIENTE_CLI_id = ? AND ROWNUM = 1";
        PreparedStatement psCheck = con.prepareStatement(sqlCheck);
        psCheck.setInt(1, idEmisor);
        ResultSet rsCheck = psCheck.executeQuery();

        if (rsCheck.next()) {
            double saldoActual = rsCheck.getDouble("CUE_saldo");
            int idCuentaEmisor = rsCheck.getInt("CUE_id");

            if (saldoActual >= monto) {
                // 4. BUSCAR AL RECEPTOR
                String sqlReceptor = "SELECT CLIENTE_CLI_id FROM TARJETA WHERE TJS_numero = ?";
                PreparedStatement psReceptor = con.prepareStatement(sqlReceptor);
                psReceptor.setString(1, cuentaDestino);
                ResultSet rsReceptor = psReceptor.executeQuery();

                if (rsReceptor.next()) {
                    int idReceptor = rsReceptor.getInt("CLIENTE_CLI_id");

                    // 5. ACTUALIZAR SALDOS
                    // Restar al emisor
                    PreparedStatement psSub = con.prepareStatement("UPDATE CUENTAS SET CUE_saldo = CUE_saldo - ? WHERE CLIENTE_CLI_id = ?");
                    psSub.setDouble(1, monto);
                    psSub.setInt(2, idEmisor);
                    psSub.executeUpdate();

                    // Sumar al receptor
                    PreparedStatement psAdd = con.prepareStatement("UPDATE CUENTAS SET CUE_saldo = CUE_saldo + ? WHERE CLIENTE_CLI_id = ?");
                    psAdd.setDouble(1, monto);
                    psAdd.setInt(2, idReceptor);
                    psAdd.executeUpdate();

                    // 6. INSERTAR EN HISTORIAL
                    String sqlHist = "INSERT INTO HISTORIAL (HIS_ID, CUE_ID, HIS_CUENTA_DESTINO, HIS_MONTO, HIS_FECHA_HORA, HIS_TIPO) " +
                                     "VALUES (seq_historial.NEXTVAL, ?, ?, ?, CURRENT_TIMESTAMP, 'TRANSFERENCIA')";
                    PreparedStatement psHist = con.prepareStatement(sqlHist);
                    psHist.setInt(1, idCuentaEmisor);
                    psHist.setString(2, cuentaDestino);
                    psHist.setDouble(3, monto);
                    psHist.executeUpdate();

                    con.commit();
                    JOptionPane.showMessageDialog(this, "¡Transferencia Exitosa!");
                    
                    // Limpiamos los campos después del éxito
                    limpiarCampos();
                    
                } else {
                    JOptionPane.showMessageDialog(this, "La cuenta destino no existe.");
                    con.rollback();
                }
            } else {
                JOptionPane.showMessageDialog(this, "Saldo insuficiente.");
            }
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró cuenta para el ID: " + idEmisor);
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El monto debe ser un número válido.");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error crítico: " + e.getMessage());
        e.printStackTrace();
    }

    }//GEN-LAST:event_btnTranferirActionPerformed
private void limpiarCampos() {
    NumeroCuenta.setText("");
    CuadroMonto.setText("");
    // foco de nuevo en el primer campo
    NumeroCuenta.requestFocus();
}
