    private void mostrarDatosTarjeta() {
// 1. La consulta correcta según tu script de Oracle
    // Buscamos en la tabla TARJETA el número TJS_NUMERO usando el ID del cliente
    String sql = "SELECT TJS_NUMERO FROM TARJETA WHERE CLIENTE_CLI_id = ?"; 
    
    try {
        // 2. Usamos tu conexión estática de Oracle
        Connection cn = ConexionBD.conexion.conectar(); 
        
        if (cn != null) {
            PreparedStatement ps = cn.prepareStatement(sql);
            ps.setInt(1, idUsuarioLogueado); // El ID que viene del Login
            ResultSet rs = ps.executeQuery();
            
            if (rs.next()) {
                // 3. Extraemos usando el nombre exacto de la columna en Oracle
                String numTarjeta = rs.getString("TJS_NUMERO");
                
                // Formateamos para que se vea como tarjeta real (opcional)
                // Esto pone un espacio cada 4 números
                String formateado = numTarjeta.replaceAll("(.{4})", "$1 ").trim();
                
                NumeroUsuario.setText(formateado);
                
                // 4. Estética para que resalte en la tarjeta azul
                NumeroUsuario.setForeground(java.awt.Color.WHITE);
                NumeroUsuario.setFont(new java.awt.Font("OCR A Extended", 1, 20));
            } else {
                NumeroUsuario.setText("Sin Tarjeta");
            }
            cn.close();
        }
    } catch (Exception e) {
        // Esto te dirá en la consola si falta algo más
        e.printStackTrace(); 
        NumeroUsuario.setText("Error de Datos");
    }
}
  
