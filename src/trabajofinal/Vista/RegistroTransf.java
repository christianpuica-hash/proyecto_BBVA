    public void mostrarDatos() {
        DefaultTableModel modelo = (DefaultTableModel) tbHistorial.getModel();
        modelo.setRowCount(0); 

        // Consulta SQL con Triple JOIN para obtener nombres de emisor y receptor
        String sql = "SELECT h.HIS_ID, " +
                     "c_emi.CLI_NOMBRE AS EMISOR, " +
                     "c_rec.CLI_NOMBRE AS RECEPTOR, " +
                     "h.HIS_CUENTA_DESTINO, " +
                     "h.HIS_MONTO, " +
                     "h.HIS_FECHA_HORA, " +
                     "h.HIS_TIPO " +
                     "FROM HISTORIAL h " +
                     "JOIN CUENTAS cu_emi ON h.CUE_ID = cu_emi.CUE_ID " +
                     "JOIN CLIENTE c_emi ON cu_emi.CLIENTE_CLI_ID = c_emi.CLI_ID " +
                     "JOIN TARJETA t ON h.HIS_CUENTA_DESTINO = t.TJS_NUMERO " +
                     "JOIN CLIENTE c_rec ON t.CLIENTE_CLI_ID = c_rec.CLI_ID " +
                     "ORDER BY h.HIS_ID DESC";

        try (Connection cn = new conexion().conectar();
             Statement st = cn.createStatement();
             ResultSet rs = st.executeQuery(sql)) {

            // Formateadores para separar la fecha de la hora
            java.text.SimpleDateFormat sdfFecha = new java.text.SimpleDateFormat("dd/MM/yyyy");
            java.text.SimpleDateFormat sdfHora = new java.text.SimpleDateFormat("HH:mm:ss");

            while (rs.next()) {
                Object[] fila = new Object[8]; // Las 8 columnas de tu imagen
                
                fila[0] = rs.getInt("HIS_ID");               // ID
                fila[1] = rs.getString("EMISOR");            // Origen
                fila[2] = rs.getString("RECEPTOR");          // Receptor
                fila[3] = rs.getString("HIS_CUENTA_DESTINO"); // Destino
                fila[4] = rs.getDouble("HIS_MONTO");         // Monto
                
                // Procesar Fecha y Hora
                java.sql.Timestamp ts = rs.getTimestamp("HIS_FECHA_HORA");
                fila[5] = (ts != null) ? sdfFecha.format(ts) : ""; // Fecha
                fila[6] = (ts != null) ? sdfHora.format(ts) : "";  // Hora
                
                fila[7] = rs.getString("HIS_TIPO");           // Tipo
                
                modelo.addRow(fila);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Error al cargar datos: " + e.getMessage());
        }
    
}


