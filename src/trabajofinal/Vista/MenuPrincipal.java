    // Método para cargar datos desde la BD
    private void cargarDatosUsuario(int clienteId) {
    try (Connection con = conexion.conectar()) {
        // Obtener nombre del cliente
        String sqlCliente = "SELECT CLI_nombre FROM CLIENTE WHERE CLI_id = ?";
        PreparedStatement psCliente = con.prepareStatement(sqlCliente);
        psCliente.setInt(1, clienteId);
        ResultSet rsCliente = psCliente.executeQuery();

        if (rsCliente.next()) {
            NombreUsuario.setText(rsCliente.getString("CLI_nombre"));
        }

        // Obtener cuentas del cliente
        String sqlCuentas = "SELECT CUE_tipo_cuenta, CUE_saldo FROM CUENTAS WHERE CLIENTE_CLI_id = ?";
        PreparedStatement psCuentas = con.prepareStatement(sqlCuentas);
        psCuentas.setInt(1, clienteId);
        ResultSet rsCuentas = psCuentas.executeQuery();

        // Inicializamos en 0 por si no tiene alguna cuenta
        double saldoCorriente = 0;
        double saldoAhorros = 0;

        while (rsCuentas.next()) {
            String tipo = rsCuentas.getString("CUE_tipo_cuenta");
            double saldo = rsCuentas.getDouble("CUE_saldo");

            if ("CORRIENTE".equalsIgnoreCase(tipo)) {
                saldoCorriente = saldo;
            } else if ("AHORRO".equalsIgnoreCase(tipo)) {
                saldoAhorros = saldo;
            }
        }

         // Aquí mostramos solo el dinero
        lblSaldoCorriente.setText(String.valueOf("S/ " +saldoCorriente));
        lblSaldoAhorros.setText(String.valueOf("S/ " +saldoAhorros));


    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al cargar datos: " + e.getMessage());
    }
}


