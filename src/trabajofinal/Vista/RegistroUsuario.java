    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // 1. Capturar datos de la interfaz
    String nombre = jTextField2.getText().trim();
    String dni = jTextField1.getText().trim();
    String telefono = jTextField3.getText().trim();
    String usuario = jTextField4.getText().trim();
    String password = new String(jPasswordField1.getPassword());
    String tarjeta = jTextField5.getText().trim();
    String tipoCuenta = jComboBox1.getSelectedItem().toString();

    // Validar que no haya campos vacíos
    if (nombre.isEmpty() || dni.isEmpty() || usuario.isEmpty() || password.isEmpty() || tarjeta.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor, completa todos los campos obligatorios.");
        return;
    }

    Connection con = null;
    try {
        con = ConexionBD.conexion.conectar();
        con.setAutoCommit(false); // Iniciamos la transacción

        // 2. Obtener el siguiente ID disponible
        String sqlId = "SELECT MAX(CLI_id) + 1 FROM CLIENTE";
        Statement st = con.createStatement();
        ResultSet rs = st.executeQuery(sqlId);
        int nuevoId = 1; // Por si es el primer registro
        if (rs.next() && rs.getInt(1) > 0) {
            nuevoId = rs.getInt(1);
        }

        // 3. INSERT en CLIENTE
        String insCliente = "INSERT INTO CLIENTE (CLI_id, CLI_nombre, CLI_dni, CLI_telefono) VALUES (?, ?, ?, ?)";
        PreparedStatement ps1 = con.prepareStatement(insCliente);
        ps1.setInt(1, nuevoId);
        ps1.setString(2, nombre);
        ps1.setString(3, dni);
        ps1.setString(4, telefono);
        ps1.executeUpdate();

        // 4. INSERT en USUARIO
        String insUsuario = "INSERT INTO USUARIO (USU_id, USU_nombre, USU_password, CLIENTE_CLI_id) VALUES (?, ?, ?, ?)";
        PreparedStatement ps2 = con.prepareStatement(insUsuario);
        ps2.setInt(1, nuevoId);
        ps2.setString(2, usuario);
        ps2.setString(3, password);
        ps2.setInt(4, nuevoId);
        ps2.executeUpdate();

        // 5. INSERT en CUENTAS (Saldo inicial 0)
        String insCuenta = "INSERT INTO CUENTAS (CUE_id, CUE_tipo_cuenta, CUE_saldo, CLIENTE_CLI_id) VALUES (?, ?, 0, ?)";
        PreparedStatement ps3 = con.prepareStatement(insCuenta);
        ps3.setInt(1, nuevoId);
        ps3.setString(2, tipoCuenta);
        ps3.setInt(3, nuevoId);
        ps3.executeUpdate();

        // 6. INSERT en TARJETA
        String insTarjeta = "INSERT INTO TARJETA (TJS_id, CLIENTE_CLI_id, TJS_numero, TJS_tipo) VALUES (?, ?, ?, 'DEBITO')";
        PreparedStatement ps4 = con.prepareStatement(insTarjeta);
        ps4.setInt(1, nuevoId);
        ps4.setInt(2, nuevoId);
        ps4.setString(3, tarjeta);
        ps4.executeUpdate();

        con.commit(); // Si todo salió bien, guardamos en la BD
        JOptionPane.showMessageDialog(this, "¡Usuario " + usuario + " registrado con éxito!");
        
        // Limpiar campos o volver al login
        new LoginPrincipal().setVisible(true);
        this.dispose();

    } catch (Exception e) {
        try {
            if (con != null) con.rollback(); // Si algo falló, deshacemos todo
        } catch (SQLException ex) {
            System.out.println("Error en rollback: " + ex.getMessage());
        }
        JOptionPane.showMessageDialog(this, "Error al registrar: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

